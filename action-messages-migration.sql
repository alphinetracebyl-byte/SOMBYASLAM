-- ─────────────────────────────────────────────────────────────────────────────
-- Action Center — action_messages table
-- Run in: Supabase Dashboard → SQL Editor
--
-- Purpose: General-purpose request/messaging system allowing any authenticated
--          user (field inspector, vet, ministry staff, farmer) to send a
--          request to any other user or group of users, and for the recipient
--          to respond.  Messages may reference a livestock domain object
--          (movement, animal, inspection, premises, destination check).
-- ─────────────────────────────────────────────────────────────────────────────

BEGIN;

-- ── Main table ────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS action_messages (
  id                UUID        PRIMARY KEY DEFAULT gen_random_uuid(),

  -- Human-readable message code (e.g. MSG-BAR-26-000001)
  -- Generated by generate_message_code() before insert.
  message_code      TEXT        NOT NULL UNIQUE,

  -- ── Sender ─────────────────────────────────────────────────────────────────
  -- from_user_id links to Supabase auth.users; kept nullable so the row can
  -- be staged before the session UUID is resolved, but must be set on insert.
  from_user_id      UUID        NOT NULL,
  from_user_name    TEXT        NOT NULL,
  from_role         TEXT,                          -- e.g. FIELD_INSPECTOR, VET
  from_region       TEXT,                          -- region code of the sender

  -- ── Recipient (flexible routing) ───────────────────────────────────────────
  -- A message may target a specific user (to_user_id), a role (to_role),
  -- a region (to_region), or any combination.  At least one must be set.
  -- to_user_id = NULL means the message is broadcast to a role/region group.
  to_user_id        UUID,                          -- NULL for role broadcasts
  to_user_name      TEXT,                          -- denormalised display name
  to_role           TEXT,                          -- e.g. FIELD_INSPECTOR
  to_region         TEXT,                          -- e.g. BAR, MUD, AWD

  -- ── Content ────────────────────────────────────────────────────────────────
  subject           TEXT        NOT NULL,
  body              TEXT        NOT NULL,

  -- ── Priority ───────────────────────────────────────────────────────────────
  priority          TEXT        NOT NULL DEFAULT 'NORMAL'
                    CHECK (priority IN ('LOW', 'NORMAL', 'HIGH', 'URGENT')),

  -- ── Domain object reference (optional) ────────────────────────────────────
  -- Links the message to a specific livestock record for quick navigation.
  ref_type          TEXT
                    CHECK (ref_type IN (
                      'MOVEMENT', 'ANIMAL', 'INSPECTION',
                      'PREMISES', 'DESTINATION_CHECK'
                    )),
  ref_code          TEXT,                          -- business code of the object

  -- ── Workflow status ────────────────────────────────────────────────────────
  status            TEXT        NOT NULL DEFAULT 'UNREAD'
                    CHECK (status IN ('UNREAD', 'READ', 'RESPONDED', 'CLOSED')),

  -- ── Response ───────────────────────────────────────────────────────────────
  response_body     TEXT,
  responded_by_id   UUID,
  responded_by_name TEXT,
  responded_at      TIMESTAMPTZ,

  -- ── Audit timestamps (UTC) ─────────────────────────────────────────────────
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE action_messages IS
  'Action Center messages. Any authenticated user can send a request to another '
  'user or to a role/region group. Recipients respond inline. Supports direct '
  'messages (to_user_id set) and role broadcasts (to_role / to_region set).';

COMMENT ON COLUMN action_messages.message_code    IS 'Human-readable code: MSG-<REG>-<YY>-<SEQ6>, generated by generate_message_code().';
COMMENT ON COLUMN action_messages.from_user_id    IS 'Supabase auth.uid() of the sender; enforced by RLS INSERT policy.';
COMMENT ON COLUMN action_messages.to_user_id      IS 'NULL for role/region broadcasts; set for direct user messages.';
COMMENT ON COLUMN action_messages.ref_type        IS 'Domain object type this message relates to (optional).';
COMMENT ON COLUMN action_messages.ref_code        IS 'Business code of the referenced domain object (optional).';
COMMENT ON COLUMN action_messages.status          IS 'UNREAD → READ → RESPONDED → CLOSED lifecycle.';

-- ── Indexes ───────────────────────────────────────────────────────────────────

-- Fast inbox lookup: messages sent by a user
CREATE INDEX IF NOT EXISTS idx_am_from_user
  ON action_messages (from_user_id);

-- Fast inbox lookup: messages addressed to a specific user
CREATE INDEX IF NOT EXISTS idx_am_to_user
  ON action_messages (to_user_id);

-- Role-broadcast lookup: find all messages targeting a role in a region
-- (used by role-based inboxes where to_user_id IS NULL)
CREATE INDEX IF NOT EXISTS idx_am_to_role_region
  ON action_messages (to_role, to_region);

-- Status-based filtering (unread counts, inbox views)
CREATE INDEX IF NOT EXISTS idx_am_status
  ON action_messages (status);

-- Chronological feed (newest first)
CREATE INDEX IF NOT EXISTS idx_am_created_at_desc
  ON action_messages (created_at DESC);

-- ── Row-level security ────────────────────────────────────────────────────────
ALTER TABLE action_messages ENABLE ROW LEVEL SECURITY;

DO $$ BEGIN

  -- SELECT: a user can see any message they sent OR that was addressed to them.
  -- Role-broadcast messages (to_user_id IS NULL) must be handled at the
  -- application layer by querying on (to_role, to_region) after this policy
  -- grants access, or via a separate RPC that runs SECURITY DEFINER.
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
     WHERE tablename = 'action_messages' AND policyname = 'am_select'
  ) THEN
    CREATE POLICY am_select ON action_messages
      FOR SELECT TO authenticated
      USING (
        from_user_id = auth.uid()
        OR to_user_id = auth.uid()
      );
  END IF;

  -- INSERT: a user may only send a message as themselves.
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
     WHERE tablename = 'action_messages' AND policyname = 'am_insert'
  ) THEN
    CREATE POLICY am_insert ON action_messages
      FOR INSERT TO authenticated
      WITH CHECK (from_user_id = auth.uid());
  END IF;

  -- UPDATE: sender may close the message; recipient may respond or close.
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
     WHERE tablename = 'action_messages' AND policyname = 'am_update'
  ) THEN
    CREATE POLICY am_update ON action_messages
      FOR UPDATE TO authenticated
      USING (
        to_user_id = auth.uid()
        OR from_user_id = auth.uid()
      );
  END IF;

END $$;

-- ── Message code generator ────────────────────────────────────────────────────
-- Format : MSG-<REG3>-<YY>-<SEQ6>
-- Example: MSG-BAR-26-000001
--
-- Uses a simple MAX()+1 counter scoped to region+year, consistent with the
-- pattern used by generate_inspection_code() in this project.
-- For very high concurrency, replace with somlits_next_seq() from
-- somlits-id-generation.sql using entity_type = 'MSG'.
CREATE OR REPLACE FUNCTION generate_message_code(p_region TEXT DEFAULT 'SOM')
RETURNS TEXT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_year TEXT := TO_CHAR(NOW() AT TIME ZONE 'UTC', 'YY');
  v_reg  TEXT := UPPER(LEFT(COALESCE(NULLIF(TRIM(p_region), ''), 'SOM'), 3));
  v_seq  BIGINT;
  v_prefix TEXT;
BEGIN
  v_prefix := 'MSG-' || v_reg || '-' || v_year || '-';

  -- Atomic read-and-increment: lock the relevant rows to avoid duplicates
  -- under concurrent inserts in the same region+year bucket.
  SELECT COALESCE(
           MAX(
             CAST(
               SPLIT_PART(message_code, '-', 4)
             AS BIGINT)
           ), 0
         ) + 1
    INTO v_seq
    FROM action_messages
   WHERE message_code LIKE v_prefix || '%';

  RETURN v_prefix || LPAD(v_seq::TEXT, 6, '0');
END;
$$;

COMMENT ON FUNCTION generate_message_code(TEXT) IS
  'Generates a sequential Action Center message code: MSG-<REG3>-<YY>-<SEQ6>. '
  'Pass the sender''s region code (e.g. ''BAR'', ''MUD''). '
  'Falls back to ''SOM'' when region is blank. '
  'Call this RPC before inserting a row and pass the result as message_code.';

GRANT EXECUTE ON FUNCTION generate_message_code(TEXT) TO authenticated;

-- ── updated_at auto-maintenance trigger ───────────────────────────────────────
-- Keeps updated_at current whenever any column changes, so clients can sort or
-- poll by modification time without additional bookkeeping.
CREATE OR REPLACE FUNCTION am_set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

DO $$ BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_trigger
     WHERE tgname = 'trg_am_updated_at'
       AND tgrelid = 'action_messages'::regclass
  ) THEN
    CREATE TRIGGER trg_am_updated_at
      BEFORE UPDATE ON action_messages
      FOR EACH ROW EXECUTE FUNCTION am_set_updated_at();
  END IF;
END $$;

COMMIT;
